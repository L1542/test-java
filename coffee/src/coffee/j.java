package musicplaylist;

// ============================================================================
// โปรแกรมเพลย์ลิสต์เพลงบน Console
// ใช้ Doubly Linked List (รายการเชื่อมโยงสองทิศทาง) เก็บชื่อเพลง
//
// แนวคิดหลัก:
//   - แต่ละเพลงเป็นโหนด (Node) ที่มี pointer ชี้ไปเพลงก่อนหน้า (prev)
//     และเพลงถัดไป (next)
//   - Playlist เก็บตัวชี้หลัก 3 ตัว คือ head (เพลงแรก), tail (เพลงสุดท้าย)
//     และ current (เพลงที่กำลังเล่น)
//   - การเพิ่ม/ลบ/เลื่อนเพลง ทำได้โดยปรับ pointer ไม่ต้องย้ายข้อมูลทั้งลิสต์
// ============================================================================
import java.util.Scanner;

public class MusicPlaylist {

        // ====================================================================
        // Node: แทนเพลงหนึ่งเพลงในลิสต์
        //
        // ตัวอย่างโครงสร้างเมื่อมี 3 เพลง [A, B, C]:
        //   null <- [A] <-> [B] <-> [C] -> null
        //   A.prev = null, A.next = B
        //   B.prev = A,    B.next = C
        //   C.prev = B,    C.next = null
        // ====================================================================
        static class Node {
            String title;       // ชื่อเพลง เก็บเป็นข้อความธรรมดา
            Node prev;          // อ้างอิงถึงโหนดก่อนหน้า (null ถ้าเป็นเพลงแรก)
            Node next;          // อ้างอิงถึงโหนดถัดไป (null ถ้าเป็นเพลงสุดท้าย)

            // Constructor: สร้างโหนดใหม่โดยกำหนดชื่อเพลง
            // prev และ next จะเป็น null โดยอัตโนมัติ จนกว่าจะถูกผูกเข้าลิสต์
            Node(String title) {
                this.title = title;
            }

            // Override toString() เพื่อให้เวลาเรียก println(node) หรือ "" + node
            // จะได้ชื่อเพลงออกมาโดยตรง ไม่ใช่ชื่อคลาสกับ hash code
            @Override
            public String toString() {
                return title;
            }
        }

        // ====================================================================
        // Playlist: จัดการลิสต์เพลงทั้งหมด
        // ====================================================================
        static class Playlist {
            Node head;          // ชี้ไปเพลงแรกของลิสต์ (null ถ้าลิสต์ว่าง)
            Node tail;          // ชี้ไปเพลงสุดท้ายของลิสต์ (null ถ้าลิสต์ว่าง)
            Node current;       // ชี้ไปเพลงที่กำลังเล่นอยู่ (null ถ้าลิสต์ว่าง)
            int size = 0;       // จำนวนเพลงทั้งหมดในลิสต์ ใช้เช็คว่าว่างหรือไม่

            // ----------------------------------------------------------------
            // add: เพิ่มเพลงใหม่ต่อท้ายลิสต์
            //
            // ความซับซ้อนเวลา: O(1) เพราะมี tail ชี้อยู่แล้ว ไม่ต้องวนหาท้ายลิสต์
            // ----------------------------------------------------------------
            void add(String title) {
                // ป้องกันข้อมูลไม่ถูกต้องในระดับ method
                // (addSong ตรวจไว้แล้ว แต่ method นี้อาจถูกเรียกจากที่อื่นได้)
                if (title == null || title.isEmpty()) {
                    throw new IllegalArgumentException("ชื่อเพลงว่างเปล่า");
                }

                // สร้างโหนดใหม่ ตอนนี้ prev = null และ next = null
                Node n = new Node(title);

                if (head == null) {
                    // กรณีลิสต์ว่าง: เพลงนี้เป็นทั้งเพลงแรกและเพลงสุดท้าย
                    // และยังเป็นเพลงที่กำลังเล่นอยู่โดยอัตโนมัติ
                    head = n;
                    tail = n;
                    current = n;
                } else {
                    // กรณีลิสต์มีเพลงอยู่แล้ว ต้องผูกโหนดใหม่ต่อจาก tail
                    // ขั้นที่ 1: ให้เพลงเดิม (tail) ชี้ไปเพลงใหม่
                    tail.next = n;
                    // ขั้นที่ 2: ให้เพลงใหม่ชี้กลับไปเพลงเดิม
                    n.prev = tail;
                    // ขั้นที่ 3: ย้าย tail ไปเป็นเพลงใหม่ เพราะตอนนี้มันคือเพลงสุดท้าย
                    tail = n;
                }
                // เพิ่มจำนวนเพลงหลังผูกเสร็จแล้ว
                size++;
            }

            // ----------------------------------------------------------------
            // search: ค้นหาเพลงจากชื่อ โดยไม่สนตัวพิมพ์เล็ก-ใหญ่
            //
            // คืนค่า: Node ของเพลงที่พบ หรือ null ถ้าไม่พบ
            // ความซับซ้อนเวลา: O(n) เพราะต้องวนหาทีละโหนด
            // ----------------------------------------------------------------
            Node search(String title) {
                // ถ้าไม่มีชื่อให้ค้น ก็ไม่มีอะไรจะหา
                if (title == null) return null;

                // เริ่มจากเพลงแรก (head) แล้วเดินตาม next ไปเรื่อย ๆ
                // หยุดเมื่อ cur เป็น null ซึ่งหมายถึงเดินพ้นเพลงสุดท้ายแล้ว
                for (Node cur = head; cur != null; cur = cur.next) {
                    // equalsIgnoreCase เปรียบเทียบโดยไม่สนตัวพิมพ์
                    // เช่น "Bohemian" กับ "BOHEMIAN" ถือว่าเท่ากัน
                    if (cur.title.equalsIgnoreCase(title)) {
                        return cur;   // พบแล้ว คืนโหนดนี้ทันที
                    }
                }
                // วนจนหมดแล้วไม่พบ
                return null;
            }

            // ----------------------------------------------------------------
            // indexOf: หาตำแหน่งของโหนดในลิสต์ โดยเริ่มนับที่ 0
            //
            // เช่น ถ้าโหนดเป็นเพลงแรก จะคืน 0 ถ้าเป็นเพลงที่สอง จะคืน 1
            // คืน -1 ถ้าโหนดนั้นไม่อยู่ในลิสต์
            //
            // หมายเหตุ: เปรียบเทียบด้วย == (อ้างอิงวัตถุ) ไม่ใช่ equals
            // เพราะต้องการรู้ว่าเป็น "โหนดตัวนั้น" จริง ๆ ไม่ใช่แค่ชื่อเหมือนกัน
            // ----------------------------------------------------------------
            int indexOf(Node target) {
                int i = 0;   // ตัวนับตำแหน่ง เริ่มที่ 0 (เพลงแรก)
                // วนไปทีละโหนด พร้อมเพิ่มตัวนับ i ทุกรอบ
                for (Node cur = head; cur != null; cur = cur.next, i++) {
                    if (cur == target) {
                        return i;   // เจอโหนดที่ต้องการ คืนตำแหน่งปัจจุบัน
                    }
                }
                return -1;   // วนจนหมดแล้วไม่เจอ
            }

            // ----------------------------------------------------------------
            // delete: ลบโหนดออกจากลิสต์
            //
            // ความซับซ้อนเวลา: O(1) เพราะรู้โหนดที่จะลบอยู่แล้ว
            // ต้องแก้ pointer ของโหนดข้างเคียงให้ "ข้าม" โหนดนี้ไป
            // ----------------------------------------------------------------
            void delete(Node n) {
                // ถ้าไม่มีโหนดให้ลบ แจ้งข้อผิดพลาด
                if (n == null) {
                    throw new IllegalArgumentException("ไม่พบเพลงที่ต้องการลบ");
                }

                // ----- ขั้นที่ 1: ย้าย current ออกจากโหนดที่กำลังจะลบ -----
                // ต้องทำก่อนขั้นอื่น เพราะหลังจากล้าง pointer ของ n แล้ว
                // จะหาเพลงข้างเคียงไม่ได้อีก
                if (current == n) {
                    // ถ้ามีเพลงถัดไป ให้ไปเพลงถัดไป
                    // ถ้าไม่มี (n เป็นเพลงสุดท้าย) ให้ย้อนไปเพลงก่อนหน้า
                    // ถ้า n เป็นเพลงเดียวในลิสต์ ทั้งคู่เป็น null จึงได้ current = null
                    current = (n.next != null) ? n.next : n.prev;
                }

                // ----- ขั้นที่ 2: แก้ pointer ฝั่งก่อนหน้า -----
                if (n.prev != null) {
                    // มีเพลงก่อนหน้า: ให้เพลงนั้นชี้ข้าม n ไปหาเพลงถัดไปของ n
                    // เช่น A -> B -> C ลบ B: A.next = C
                    n.prev.next = n.next;
                } else {
                    // ไม่มีเพลงก่อนหน้า แปลว่า n คือเพลงแรก (head)
                    // ให้ head ชี้ไปเพลงถัดไปแทน
                    head = n.next;
                }

                // ----- ขั้นที่ 3: แก้ pointer ฝั่งถัดไป -----
                if (n.next != null) {
                    // มีเพลงถัดไป: ให้เพลงนั้นชี้ย้อนข้าม n ไปหาเพลงก่อนหน้าของ n
                    // เช่น A <-> B <-> C ลบ B: C.prev = A
                    n.next.prev = n.prev;
                } else {
                    // ไม่มีเพลงถัดไป แปลว่า n คือเพลงสุดท้าย (tail)
                    // ให้ tail ชี้ไปเพลงก่อนหน้าแทน
                    tail = n.prev;
                }

                // ----- ขั้นที่ 4: ตัดโหนดที่ลบออกจากลิสต์ -----
                // ล้าง pointer ของ n ให้เป็น null เพื่อไม่ให้ยังผูกกับลิสต์
                // เมื่อไม่มีอะไรอ้างอิงถึง n แล้ว Garbage Collector จะเก็บคืนหน่วยความจำ
                n.prev = null;
                n.next = null;

                // ----- ขั้นที่ 5: ลดจำนวนเพลง -----
                size--;
            }

            // ----------------------------------------------------------------
            // isEmpty: ตรวจว่าลิสต์ไม่มีเพลงเลยหรือไม่
            // ใช้ size แทนการเช็ค head == null เพื่อให้อ่านง่ายและชัดเจน
            // ----------------------------------------------------------------
            boolean isEmpty() {
                return size == 0;
            }

            // ----------------------------------------------------------------
            // print: แสดงเพลงทั้งหมดพร้อมเลขลำดับ
            // เพลงที่กำลังเล่นจะมีข้อความ "<--- กำลังเล่น" ต่อท้าย
            //
            // ตัวอย่างผลลัพธ์:
            //   1. Bohemian Rhapsody
            //   2. Hotel California  <--- กำลังเล่น
            //   3. Imagine
            // ----------------------------------------------------------------
            void print() {
                int i = 1;   // ลำดับที่แสดงผล เริ่มที่ 1 (ต่างจาก indexOf ที่เริ่มที่ 0)
                for (Node cur = head; cur != null; cur = cur.next) {
                    // ต่อข้อความ: เลขลำดับ + ". " + ชื่อเพลง
                    // ถ้าเพลงนี้คือ current ให้ต่อข้อความเครื่องหมายกำลังเล่นด้วย
                    String mark = (cur == current) ? "  <--- กำลังเล่น" : "";
                    System.out.println(i++ + ". " + cur + mark);
                }
            }
        }

        // ====================================================================
        // InputClosedException: Exception ที่ใช้เป็นสัญญาณว่า input ถูกปิดแล้ว
        //
        // เกิดเมื่อผู้ใช้กด Ctrl+D (Mac/Linux) หรือ Ctrl+Z แล้ว Enter (Windows)
        // สืบทอด RuntimeException เพื่อไม่ต้องประกาศ throws ในทุกเมธอด
        // ====================================================================
        static class InputClosedException extends RuntimeException {}

        // ค่าคงที่ของโปรแกรม
        static final String LINE = "-----------";   // เส้นคั่นในเมนู
        static final int MAX_LENGTH = 100;          // ความยาวสูงสุดของชื่อเพลง (ตัวอักษร)

        // ตัวแปร static เป็นสถานะหลักของโปรแกรม ใช้ร่วมกันทุกเมธอด
        static Playlist playlist = new Playlist();   // ลิสต์เพลงที่ใช้งานอยู่
        static Scanner sc = new Scanner(System.in);  // ตัวอ่านข้อมูลจากคีย์บอร์ด

        // ====================================================================
        // readLine: อ่านข้อมูล 1 บรรทัดจากผู้ใช้
        //
        // - ถ้ายังมีข้อมูลให้อ่าน: อ่านบรรทัดนั้นและตัดช่องว่างหัว-ท้ายออก (trim)
        // - ถ้า input ปิดแล้ว (ไม่มีบรรทัดให้อ่าน): โยน InputClosedException
        //   เพื่อให้ main จบโปรแกรมอย่างเรียบร้อย
        // ====================================================================
        static String readLine() {
            // hasNextLine() คืน false เมื่อไม่มีบรรทัดเหลือให้อ่านแล้ว
            if (!sc.hasNextLine()) {
                throw new InputClosedException();
            }
            // nextLine() อ่านทั้งบรรทัด, trim() ตัดช่องว่างและ \t ที่หัว-ท้าย
            return sc.nextLine().trim();
        }

        // ====================================================================
        // showMenu: แสดงเมนูหลักให้ผู้ใช้เลือก
        // ====================================================================
        static void showMenu() {
            System.out.println(LINE);
            System.out.println("เพลย์ลิสต์เพลง");
            System.out.println("1. Add");
            System.out.println("2. Delete");
            System.out.println("3. Search");
            System.out.println("4. Next/Previous");
            System.out.println("0. ปิดโปรแกรม");
            System.out.println(LINE);
        }

        // ====================================================================
        // addSong: เมนู 1 รับชื่อเพลงแล้วเพิ่มเข้าลิสต์
        //
        // ตรวจสอบตามลำดับ ถ้าข้อใดไม่ผ่านจะแจ้งและจบทันที:
        //   1. ชื่อต้องไม่ว่าง
        //   2. ความยาวต้องไม่เกิน MAX_LENGTH
        //   3. ต้องไม่มีชื่อซ้ำในลิสต์ (ไม่สนตัวพิมพ์)
        // ====================================================================
        static void addSong() {
            System.out.print("กรอกชื่อเพลง : ");
            String title = readLine();

            // ตรวจที่ 1: ชื่อว่างเปล่า
            if (title.isEmpty()) {
                System.out.println("ผิดพลาด: ชื่อเพลงว่างเปล่า");
                return;
            }

            // ตรวจที่ 2: ชื่อยาวเกินกำหนด
            if (title.length() > MAX_LENGTH) {
                System.out.println("ผิดพลาด: ชื่อเพลงยาวเกินไป (สูงสุด " + MAX_LENGTH + " ตัวอักษร)");
                return;
            }

            // ตรวจที่ 3: มีเพลงชื่อนี้อยู่แล้วหรือไม่
            // search ไม่สนตัวพิมพ์ จึงกัน "Imagine" กับ "imagine" ไม่ให้ซ้ำกัน
            if (playlist.search(title) != null) {
                System.out.println("ผิดพลาด: มีเพลง \"" + title + "\" อยู่ในเพลย์ลิสต์แล้ว");
                return;
            }

            // ผ่านทุกการตรวจแล้ว จึงเพิ่มเพลงเข้าลิสต์จริง
            playlist.add(title);
            System.out.println("เพิ่มเพลง \"" + title + "\" สำเร็จ");
        }

        // ====================================================================
        // deleteSong: เมนู 2 รับชื่อเพลงแล้วลบออกจากลิสต์
        // ====================================================================
        static void deleteSong() {
            // ลิสต์ว่างไม่มีอะไรให้ลบ
            if (playlist.isEmpty()) {
                System.out.println("ผิดพลาด: เพลย์ลิสต์ว่างเปล่า");
                return;
            }

            System.out.print("กรอกชื่อเพลงที่ต้องการลบ : ");
            String title = readLine();

            if (title.isEmpty()) {
                System.out.println("ผิดพลาด: ชื่อเพลงว่างเปล่า");
                return;
            }

            // ค้นหาโหนดที่ตรงกับชื่อที่พิมพ์ (ไม่สนตัวพิมพ์)
            Node found = playlist.search(title);
            if (found == null) {
                System.out.println("ผิดพลาด: ไม่พบเพลง \"" + title + "\"");
                return;
            }

            // เก็บชื่อจริงที่บันทึกไว้ในลิสต์ก่อนลบ
            // เช่น ผู้ใช้พิมพ์ "imagine" แต่ในลิสต์เก็บ "Imagine"
            // ข้อความแจ้งผลจะแสดง "Imagine" ตามที่บันทึกไว้
            String realTitle = found.title;

            playlist.delete(found);
            System.out.println("ลบเพลง \"" + realTitle + "\" สำเร็จ");
        }

        // ====================================================================
        // searchSong: เมนู 3 ค้นหาเพลงแบบวนซ้ำ
        //
        // ผู้ใช้พิมพ์ชื่อเพลงเพื่อค้น ถ้าไม่พบให้ลองใหม่ได้เรื่อย ๆ
        // กด Enter เปล่า ๆ เพื่อกลับเมนูหลัก
        // ====================================================================
        static void searchSong() {
            if (playlist.isEmpty()) {
                System.out.println("ผิดพลาด: เพลย์ลิสต์ว่างเปล่า");
                return;
            }

            // วนลูปจนกว่าจะพบเพลงหรือผู้ใช้กด Enter เปล่า
            while (true) {
                System.out.print("ค้นหาเพลง (กด Enter เพื่อย้อนกลับ) : ");
                String title = readLine();

                // Enter เปล่า = ผู้ใช้ต้องการกลับเมนูหลัก
                if (title.isEmpty()) return;

                Node found = playlist.search(title);
                if (found != null) {
                    // พบเพลง แสดงชื่อและลำดับที่
                    System.out.println("พบเพลง!");
                    System.out.println("ชื่อเพลง : " + found.title);
                    // indexOf เริ่มนับที่ 0 จึงต้อง +1 ให้เป็นลำดับแบบคนนับ (1, 2, 3, ...)
                    System.out.println("ลำดับที่  : " + (playlist.indexOf(found) + 1));
                    return;   // พบแล้ว จบการค้นหา
                }

                // ไม่พบ ให้วนลูปถามใหม่
                System.out.println("ผิดพลาด: ไม่พบเพลง กรุณากรอกใหม่อีกครั้ง");
            }
        }

        // ====================================================================
        // nextPrevious: เมนู 4 เลื่อนเพลงที่กำลังเล่นไปข้างหน้า/ข้างหลัง
        //
        // คำสั่งที่รองรับ:
        //   N = ไปเพลงถัดไป
        //   P = ไปเพลงก่อนหน้า
        //   B = กลับเมนูหลัก
        //
        // สิ่งสำคัญ: การเลื่อนทำโดย "เดินตาม pointer" current.next / current.prev
        // ไม่ได้ใช้ index จึงเร็วและไม่ต้องกังวลเรื่อง index เปลี่ยนหลังลบเพลง
        // ====================================================================
        static void nextPrevious() {
            if (playlist.isEmpty()) {
                System.out.println("ผิดพลาด: เพลย์ลิสต์ว่างเปล่า");
                return;
            }

            // วนลูปเพื่อให้ผู้ใช้เลื่อนได้หลายครั้ง จนกว่าจะเลือก B
            while (true) {
                // แสดงรายการเพลงทั้งหมดพร้อมเครื่องหมายเพลงที่กำลังเล่น
                System.out.println("---- เพลย์ลิสต์ ----");
                playlist.print();
                System.out.println("--------------------");
                System.out.println("กำลังเล่น : " + playlist.current);
                System.out.print("[N] Next  [P] Previous  [B] Back : ");

                // toLowerCase ทำให้พิมพ์ N หรือ n ก็ได้เหมือนกัน
                String cmd = readLine().toLowerCase();

                if (cmd.equals("n")) {
                    // ถ้ามีเพลงถัดไป ให้ current เลื่อนไปที่เพลงนั้น
                    if (playlist.current.next != null) {
                        playlist.current = playlist.current.next;
                    } else {
                        // ไม่มีเพลงถัดไป แสดงว่าอยู่ที่เพลงสุดท้ายแล้ว
                        System.out.println("นี่คือเพลงสุดท้ายแล้ว");
                    }
                }
                else if (cmd.equals("p")) {
                    // ถ้ามีเพลงก่อนหน้า ให้ current ย้อนไปที่เพลงนั้น
                    if (playlist.current.prev != null) {
                        playlist.current = playlist.current.prev;
                    } else {
                        // ไม่มีเพลงก่อนหน้า แสดงว่าอยู่ที่เพลงแรกแล้ว
                        System.out.println("นี่คือเพลงแรกแล้ว");
                    }
                }
                else if (cmd.equals("b")) {
                    // ออกจากการเลื่อนเพลง กลับเมนูหลัก
                    return;
                }
                else {
                    // พิมพ์คำสั่งผิด
                    System.out.println("ผิดพลาด: คำสั่งไม่ถูกต้อง ให้ใช้ N, P หรือ B");
                }
            }
        }

        // ====================================================================
        // main: จุดเริ่มต้นของโปรแกรม และลูปเมนูหลัก
        //
        // โครงสร้าง try ซ้อนกันสองชั้น:
        //   ชั้นนอก: ดักการปิด input เพื่อจบโปรแกรม
        //   ชั้นใน:  ดักข้อผิดพลาดที่ไม่คาดคิดในแต่ละรอบเมนู แล้ววนทำงานต่อ
        // ====================================================================
        public static void main(String[] args) {
            try {
                // ลูปหลัก ทำงานต่อเนื่องจนผู้ใช้เลือก 0 หรือ input ถูกปิด
                while (true) {
                    try {
                        showMenu();
                        System.out.print("เลือกเมนู : ");
                        String input = readLine();

                        // ผู้ใช้กด Enter เปล่า ให้กรอกใหม่
                        if (input.isEmpty()) {
                            System.out.println("ผิดพลาด: กรุณากรอกตัวเลข");
                            continue;   // ข้ามไปรอบถัดไปของ while
                        }

                        // แปลงข้อความเป็นตัวเลข
                        // ถ้าไม่ใช่ตัวเลข เช่น "abc" จะโยน NumberFormatException
                        int choice;
                        try {
                            choice = Integer.parseInt(input);
                        } catch (NumberFormatException e) {
                            System.out.println("ผิดพลาด: \"" + input + "\" ไม่ใช่ตัวเลขที่ถูกต้อง");
                            continue;   // กรอกใหม่
                        }

                        // เลือกฟังก์ชันตามเลขเมนู
                        switch (choice) {
                            case 1: addSong();      break;
                            case 2: deleteSong();   break;
                            case 3: searchSong();   break;
                            case 4: nextPrevious(); break;
                            case 0:
                                System.out.println("ลาก่อน!");
                                return;   // จบ main ทันที ทำให้ finally ทำงาน
                            default:
                                System.out.println("ผิดพลาด: เลขไม่ถูกต้อง เลือกได้ 0-4");
                        }

                    // ชั้นใน: ถ้าเป็นการปิด input ให้โยนต่อไปชั้นนอก
                    // ห้ามจับเป็นข้อผิดพลาดทั่วไป เพราะจะทำให้โปรแกรมไม่จบ
                    } catch (InputClosedException e) {
                        throw e;

                    // ข้อผิดพลาดอื่นที่ไม่คาดคิด เช่น NullPointerException
                    // แสดงข้อความแล้วกลับไปเริ่มรอบเมนูใหม่ โปรแกรมไม่หยุดทำงาน
                    } catch (RuntimeException e) {
                        System.out.println("เกิดข้อผิดพลาดที่ไม่คาดคิด: " + e.getMessage());
                    }
                }

            // ชั้นนอก: จับการปิด input แล้วแสดงข้อความลาก่อน
            } catch (InputClosedException e) {
                System.out.println("\nปิดการรับข้อมูลแล้ว ลาก่อน!");

            // finally ทำงานเสมอ ไม่ว่าจะจบด้วย return, exception หรือปกติ
            // ปิด Scanner เพื่อคืนทรัพยากรและปิดการอ่านจาก System.in
            } finally {
                sc.close();
            }
        }
}
